#!/usr/bin/env bash
# Prepare a local APP_MODE=production env with two browser origins (no Docker).
# Does NOT touch ./data/arcvale-sandbox.db or its FILES_DIR.
#
# Why two origins: server/config.ts rejects CRM_ORIGIN === PUBLIC_ORIGIN.
# Local dual-host (documented): https://localhost:<port> vs https://127.0.0.1:<port>
# Production mode also requires https:// (http:// was why a same-host attempt failed).
#
# Usage:
#   ./deploy/configure-local-production.sh
#   WEB_PORT=43127 PORT=8742 ./deploy/configure-local-production.sh
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
# shellcheck source=lib.sh
source "$ROOT/deploy/lib.sh"

WEB_PORT="${WEB_PORT:-43127}"
API_PORT="${PORT:-8742}"
ENV_FILE="${ENV_FILE:-$ROOT/.env.local.production}"
CERT_DIR="$ROOT/.local-certs"
SECRETS_DIR="$ROOT/secrets"

PUBLIC_ORIGIN="https://localhost:${WEB_PORT}"
CRM_ORIGIN="https://127.0.0.1:${WEB_PORT}"

if [[ "$PUBLIC_ORIGIN" == "$CRM_ORIGIN" ]]; then
  log_err "PUBLIC_ORIGIN and CRM_ORIGIN must differ (use localhost vs 127.0.0.1)."
  exit 2
fi

mkdir -p "$CERT_DIR" "$SECRETS_DIR" "$ROOT/data/production-files" "$ROOT/backups"
chmod 700 "$SECRETS_DIR" "$CERT_DIR" 2>/dev/null || true

if [[ ! -f "$CERT_DIR/cert.pem" || ! -f "$CERT_DIR/key.pem" ]]; then
  log "Generating local TLS cert under .local-certs/ (gitignored)…"
  openssl req -x509 -newkey rsa:2048 -nodes \
    -keyout "$CERT_DIR/key.pem" \
    -out "$CERT_DIR/cert.pem" \
    -days 825 \
    -subj "/CN=localhost" \
    -addext "subjectAltName=DNS:localhost,IP:127.0.0.1" \
    >/dev/null 2>&1
  chmod 600 "$CERT_DIR/key.pem" "$CERT_DIR/cert.pem"
fi

# Preserve existing secrets across re-runs.
EXISTING_SESSION=""
EXISTING_DEK=""
if [[ -f "$ENV_FILE" ]]; then
  EXISTING_SESSION="$(env_get SESSION_SECRET "$ENV_FILE")"
  EXISTING_DEK="$(env_get DATA_ENCRYPTION_KEY "$ENV_FILE")"
fi

umask 077
cat >"$ENV_FILE" <<EOF
# Local production dual-host (generated by deploy/configure-local-production.sh).
# Do not commit. Sandbox DB at ./data/arcvale-sandbox.db is not used here.
APP_MODE=production
NODE_ENV=production
PUBLIC_DOMAIN=localhost
CRM_DOMAIN=127.0.0.1
ACME_EMAIL=local-dev@localhost
PUBLIC_ORIGIN=${PUBLIC_ORIGIN}
CRM_ORIGIN=${CRM_ORIGIN}
HOST=127.0.0.1
PORT=${API_PORT}
WEB_PORT=${WEB_PORT}
DATABASE_PATH=${ROOT}/data/arcvale-production.db
FILES_DIR=${ROOT}/data/production-files
RATES_SOURCE=coingecko
TRUST_PROXY=false
LOG_LEVEL=info
MANUAL_REVIEW_THRESHOLD_USD=10000
LOCAL_HTTPS=1
LOCAL_TLS_KEY=${CERT_DIR}/key.pem
LOCAL_TLS_CERT=${CERT_DIR}/cert.pem
EOF
chmod 600 "$ENV_FILE"

if [[ -n "$EXISTING_SESSION" ]] && ! is_placeholder "$EXISTING_SESSION"; then
  printf 'SESSION_SECRET=%s\n' "$EXISTING_SESSION" >>"$ENV_FILE"
  log "SESSION_SECRET preserved."
else
  printf 'SESSION_SECRET=%s\n' "$(generate_session_secret)" >>"$ENV_FILE"
  log "Generated SESSION_SECRET (not printed)."
fi

if [[ -n "$EXISTING_DEK" ]] && ! is_placeholder "$EXISTING_DEK"; then
  printf 'DATA_ENCRYPTION_KEY=%s\n' "$EXISTING_DEK" >>"$ENV_FILE"
  log "DATA_ENCRYPTION_KEY preserved."
elif [[ -f "$SECRETS_DIR/DATA_ENCRYPTION_KEY.local-production.offline" ]]; then
  key="$(tr -d '\n' <"$SECRETS_DIR/DATA_ENCRYPTION_KEY.local-production.offline")"
  printf 'DATA_ENCRYPTION_KEY=%s\n' "$key" >>"$ENV_FILE"
  log "Restored DATA_ENCRYPTION_KEY from secrets/DATA_ENCRYPTION_KEY.local-production.offline"
else
  key="$(generate_data_encryption_key)"
  printf 'DATA_ENCRYPTION_KEY=%s\n' "$key" >>"$ENV_FILE"
  printf '%s\n' "$key" >"$SECRETS_DIR/DATA_ENCRYPTION_KEY.local-production.offline"
  chmod 600 "$SECRETS_DIR/DATA_ENCRYPTION_KEY.local-production.offline"
  log "Generated DATA_ENCRYPTION_KEY (not printed); offline copy in secrets/"
fi

chmod 600 "$ENV_FILE"

pub="$(env_get PUBLIC_ORIGIN "$ENV_FILE")"
crm="$(env_get CRM_ORIGIN "$ENV_FILE")"
log ""
log "Local production env ready:"
log "  file:          $ENV_FILE"
log "  PUBLIC_ORIGIN: $pub  (customer)"
log "  CRM_ORIGIN:    $crm  (CRM)"
log "  DATABASE_PATH: $(env_get DATABASE_PATH "$ENV_FILE")"
log "  FILES_DIR:     $(env_get FILES_DIR "$ENV_FILE")"
log "  sandbox DB:    ./data/arcvale-sandbox.db (untouched; mode=sandbox)"
log ""
log "Validate: set -a && source .env.local.production && set +a && node dist-server/cli.js check-config"
log "Run:      ./deploy/run-local-production.sh"
